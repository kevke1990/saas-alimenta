export type Historical2006ChildTable = keyof typeof HISTORICAL_2006_H2_CHILD_COST_TABLES;

export function getHistorical2006H2ChildCostTable(children: number) {
  if (!Number.isInteger(children) || children < 1) {
    throw new Error("Aantal kinderen moet minimaal 1 zijn.");
  }
  return HISTORICAL_2006_H2_CHILD_COST_TABLES[Math.min(children, 4) as Historical2006ChildTable];
}
